    private void BtnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnLoginActionPerformed
        playSound("clickButton.wav");
        username1 = username.getText();
        password1 = new String(password.getPassword());
           
        if (!username1.isEmpty() && !password1.isEmpty()){
            try {
                String sqlFindAcc = "Select * from account where username = ? and password = ?";
                String sqlSoundMusic = "Select * from account where username = '"+username1+"'";

                Connection con = DriverManager.getConnection("jdbc:derby://localhost:1527/ViperDB","root","root");
                Statement st = con.createStatement();
                PreparedStatement pst = con.prepareStatement(sqlFindAcc);
                pst.setString(1, username1);
                pst.setString(2, password1);
                ResultSet rs = pst.executeQuery();
                ResultSet rs1 = st.executeQuery(sqlSoundMusic);

                if (rs.next()){
                    showCustomSuccess("Login Successful!");
                    //JOptionPane.showMessageDialog(null, "Login Successfuly", "Login Successful", JOptionPane.INFORMATION_MESSAGE);
                    while (rs1.next()){
                        username1 = rs1.getString("username");
                        password1 = rs1.getString("password");
                        easyscore = rs1.getInt("easyscore");
                        mediumscore = rs1.getInt("mediumscore");
                        hardscore = rs1.getInt("hardscore");
                        blitzscore = rs1.getString("blitzscore");
                        coins = rs1.getInt("coins");
                        pwr1 = rs1.getInt("power1");
                        pwr2 = rs1.getInt("power2");
                        pwr3 = rs1.getInt("power3");
                        sound = rs1.getInt("sound");
                        music = rs1.getInt("music");
                    }
                    
                    menu m1 = new menu();
                    m1.LblAccountUsername.setText(username1);
                    m1.setVisible(true);
                    m1.setLocationRelativeTo(null);
                    m1.setDefaultCloseOperation(JFrame.EXIT_ON_CLOSE);
                    
                    dispose();
                } else {
                    showCustomError("Account does not exist");
                    //JOptionPane.showMessageDialog(null, "Account does not exist", "Error", JOptionPane.ERROR_MESSAGE);
                    username.setText("");
                    password.setText("");
                }
                con.close();
                pst.close();
                rs.close();

            }catch (SQLException ex){
                ex.printStackTrace();
            }
        }else {

            showCustomError("Fields cannot be Empty");
//            JOptionPane.showMessageDialog(null, "Fields cannot be Empty", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_BtnLoginActionPerformed

